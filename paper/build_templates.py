def split_source(src_doc) -> dict[str, list]:
    """Cut the pandoc body at the marker paragraphs."""
    parts: dict[str, list] = {"ABSTRACTIJIES": [], "ABSTRACTFUTECH": [], "BODYBEGIN": []}
    cur = None
    for el in src_doc.element.body.iterchildren():
        if el.tag == qn("w:sectPr"):
            continue
        t = para_text(el).strip() if el.tag == qn("w:p") else ""
        if t in parts:
            cur = t; continue
        if cur:
            parts[cur].append(el)
    return parts


def abstract_runs(w: Writer, paras: list, pt: float) -> list:
    runs = []
    for p in paras:
        runs += w._runs_of(p, pt)
    return runs


def check_abstract(paras, lo, hi, name):
    words = " ".join(para_text(p) for p in paras).split()
    n = len(words)
    if not (lo <= n <= hi):
        sys.exit(f"{name} abstract has {n} words, template allows {lo}-{hi}")
    print(f"{name} abstract: {n} words")


def build_ijies(src_docx: Path, keywords: str):
    spec = spec_ijies()
    w = Writer(spec, src_docx, keywords)
    parts = split_source(w.src)
    check_abstract(parts["ABSTRACTIJIES"], *spec.abstract_words, "IJIES")
    body = w.body
    children = list(body.iterchildren())
    paras = [c for c in children if c.tag == qn("w:p")]

    # front matter paragraphs of the template, by position
    title_p, authors_p, affil1_p, affil2_p, corr_p, abs_p, kw_p = (
        paras[1], paras[3], paras[5], paras[6], paras[7], paras[10], paras[11])
    F = spec.font
    w.fill_par(title_p, [(TITLE, True, False, False)], F, 14)
    w.fill_par(authors_p, [("Dhayanidhi Rajasekaran", True, False, False), ("1*", True, False, True),
                           ("          ", True, False, False),
                           ("Rajalakshmi N.R.", True, False, False), ("2", True, False, True)], F, 11)
    w.fill_par(affil1_p, [("1", False, True, True), ("Research Scholar, " + AFFIL, False, True, False)], F, 10.5)
    w.fill_par(affil2_p, [("2", False, True, True), ("Professor, " + AFFIL, False, True, False)], F, 10.5)
    w.fill_par(corr_p, [("* Corresponding author\u2019s Email: " + EMAIL, False, False, False)], F, 10)
    w.fill_par(abs_p, [("Abstract: ", True, False, False)] + abstract_runs(w, parts["ABSTRACTIJIES"], 10), F, 10)
    w.fill_par(kw_p, [("Keywords: ", True, False, False), (keywords, False, False, False)], F, 10)

    # the running header carries sample editorial dates, which the journal fills in
    for section in w.doc.sections:
        for hp in section.header.paragraphs:
            if "Received:" in hp.text:
                runs = hp.runs
                seen_revised = False
                for i, r in enumerate(runs):
                    seen_revised = seen_revised or "Revised" in r.text
                    done = seen_revised and r.text.endswith(".")
                    r.text = "Received:" + " " * 16 + "Revised:" if i == 0 else ""
                    if done:
                        break
        for fp in section.footer.paragraphs:
            if "10.22266" in fp.text:
                for r in fp.runs:
                    if "10.22266" in r.text:
                        r.text = "DOI:"
                    elif r.text in ("9", ".xxxx.xx"):
                        r.text = ""

    # the section that ends the front matter must stay single column. The
    # body sectPr (end of document) becomes the two-column one.
    two_col = None
    for p in paras:
        sp = p.find(".//" + qn("w:sectPr"))
        if sp is not None and sp.find(qn("w:cols")) is not None and sp.find(qn("w:cols")).get(qn("w:num")) == "2":
            two_col = copy.deepcopy(sp)
    body_sect = body.find(qn("w:sectPr"))
    body.replace(body_sect, two_col)

    # remove every template element after the front-matter section break
    first_sect_par = next(p for p in paras if p.find(".//" + qn("w:sectPr")) is not None)
    idx = list(body).index(first_sect_par)
    for el in list(body)[idx + 1:]:
        if el.tag != qn("w:sectPr"):
            body.remove(el)

    w.convert_body(parts["BODYBEGIN"])
    # pandoc leaves the references at the end of the body under Bibliography
    # style and they were emitted in place. Insert the heading before them.
    w.emit_back_matter()
    move_references_last(w)
    w.save()


def build_futech(src_docx: Path, keywords: str):
    spec = spec_futech()
    w = Writer(spec, src_docx, keywords)
    parts = split_source(w.src)
    check_abstract(parts["ABSTRACTFUTECH"], *spec.abstract_words, "Futech")
    body = w.body
    children = list(body.iterchildren())
    paras = [c for c in children if c.tag == qn("w:p")]
    F = spec.font
    # 2 "Article", 3 title, 4 authors, 5-7 affiliations, table = article info
    w.fill_par(paras[3], [(TITLE, True, False, False)], F, 22)
    w.fill_par(paras[4], [("Dhayanidhi Rajasekaran", True, False, False), ("1*", True, False, True),
                          (", Rajalakshmi N.R.", True, False, False), ("2", True, False, True)], F, 12)
    w.fill_par(paras[5], [("1", False, False, True), ("Research Scholar, " + AFFIL, False, False, False)], F, 10)
    w.fill_par(paras[6], [("2", False, False, True), ("Professor, " + AFFIL, False, False, False)], F, 10)
    body.remove(paras[7])

    # sample publication metadata (issue line, DOI) is filled in by the
    # publisher, so the sample values are blanked rather than kept
    for p in body.iter(qn("w:p")):
        t = para_text(p)
        if "Volume 01" in t or "doi.org/10.55670" in t:
            for r in p.findall(qn("w:r")):
                if r.find(".//" + qn("w:drawing")) is None:
                    p.remove(r)
    for section in w.doc.sections:
        for hp in section.header.paragraphs:
            if "First author" in hp.text:
                blank = False
                for r in hp.runs:
                    if "First author" in r.text:
                        r.text = r.text.replace("First author", "Rajasekaran")
                    if r.text.strip() == "May":
                        blank = True
                    if blank:
                        r.text = ""

    info = w.doc.tables[0]
    left, right = info.rows[0].cells
    for p in left.paragraphs:
        t = p.text.strip()
        if t.startswith("3-6 keywords"):
            w.fill_par(p._p, [(keywords, False, False, False)], F, 9)
        elif t.startswith("Email address"):
            w.fill_par(p._p, [("Email address: " + EMAIL, False, False, False)], F, 9)
        elif t.startswith("Received 00"):
            w.fill_par(p._p, [("Received", False, False, False)], F, 9)
        elif t.startswith("00 April") or t.startswith("DOI:"):
            p._p.getparent().remove(p._p)
        elif t.startswith("Accepted 00"):
            w.fill_par(p._p, [("Accepted", False, False, False)], F, 9)
    rp = right.paragraphs
    # keep "A B S T R A C T" and the blank line, replace the rest by the abstract
    for p in rp[2:]:
        p._p.getparent().remove(p._p)
    abs_p = copy.deepcopy(rp[1]._p)
    right._tc.append(abs_p)
    w.fill_par(abs_p, abstract_runs(w, parts["ABSTRACTFUTECH"], 9), F, 9)
    abs_p.find(qn("w:pPr")).append(_el("w:jc", **{"w:val": "both"}))

    first_sect_par = next(p for p in paras if p.find(".//" + qn("w:sectPr")) is not None)
    idx = list(body).index(first_sect_par)
    for el in list(body)[idx + 1:]:
        if el.tag != qn("w:sectPr"):
            body.remove(el)

    w.convert_body(parts["BODYBEGIN"])
    w.emit_back_matter()
    move_references_last(w)
    blank_sample_text(w, ("10.55670",))
    w.save()


def blank_sample_text(w: Writer, needles):
    """Blank text runs carrying sample publisher metadata in the body and in
    every header and footer, including text boxes."""
    roots = [w.doc.element]
    for s in w.doc.sections:
        roots += [s.header._element, s.footer._element,
                  s.first_page_header._element, s.first_page_footer._element]
    for root in roots:
        for t in root.iter(qn("w:t")):
            if t.text and any(n in t.text for n in needles):
                t.text = ""


def move_references_last(w: Writer):
    """References were converted in place (before the back matter). Move them
    after the back matter under a 'References' heading, as both templates ask."""
    body = w.body
    refs = w.ref_pars
    if not refs:
        return
    sect = body.find(qn("w:sectPr"))
    head = _para(_ppr(align="left", before=240, after=120, keep_next=True),
                 [_run("References", w.spec.font, w.spec.h1_pt, bold=True)])
    body.insert(list(body).index(sect), head)
    for p in refs:
        body.remove(p)
        body.insert(list(body).index(sect), p)


def main(argv):
    which = set(argv[1:]) or {"ijies", "futech"}
    prep = prepare_latex()
    tmp = PAPER / ".templates_pandoc.docx"
    run_pandoc(prep.latex, tmp)
    if "ijies" in which:
        build_ijies(tmp, prep.keywords)
    if "futech" in which:
        build_futech(tmp, prep.keywords)
    tmp.unlink()


if __name__ == "__main__":
    main(sys.argv)
