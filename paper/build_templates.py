@dataclass
class Prepared:
    latex: str
    keywords: str


def _split_rows(body: str) -> list[str]:
    return re.split(r"\\\\(?![a-zA-Z])", body)


def prepare_latex() -> Prepared:
    src = (PAPER / "body.tex").read_text()

    kw = re.search(r"\\begin{IEEEkeywords}(.*?)\\end{IEEEkeywords}", src, re.S).group(1)
    keywords = " ".join(kw.split()).rstrip(".")
    src = re.sub(r"\\begin{abstract}.*?\\end{abstract}\s*", "", src, flags=re.S)
    src = re.sub(r"\\begin{IEEEkeywords}.*?\\end{IEEEkeywords}\s*", "", src, flags=re.S)
    src = re.sub(r"\\section\*{Acknowledgment}.*", "", src, flags=re.S)

    labels: dict[str, str] = {}

    # sections
    s1 = s2 = 0
    def sec(m):
        nonlocal s1, s2
        if m.group(1) == "section":
            s1 += 1; s2 = 0; num = f"{s1}"
        else:
            s2 += 1; num = f"{s1}.{s2}"
        lab = re.match(r"\s*\\label{([^}]*)}", src[m.end():])
        if lab:
            labels[lab.group(1)] = num
        return m.group(0)
    for m in re.finditer(r"\\(section|subsection){([^}]*)}", src):
        sec(m)

    # figures and tables, in source order, span flag from the starred form
    counters = {"figure": 0, "table": 0}
    def float_env(m):
        kind, star = m.group(1), m.group(2)
        counters[kind] += 1
        n = counters[kind]
        lab = re.search(r"\\label{([^}]*)}", m.group(0))
        if lab:
            labels[lab.group(1)] = str(n)
        inner = m.group(0)
        span = bool(star)
        if kind == "table":
            cols = re.search(r"begin{tabular}{([^}]*)}", inner)
            if cols is None:
                inc = re.search(r"\\input{([^}]*)}", inner)
                cols = re.search(r"begin{tabular}{([^}]*)}", (PAPER / (inc.group(1) + ".tex")).read_text())
            ncol = len(re.findall(r"[lrc]|p{[^}]*}", cols.group(1)))
            span = span or ncol > 4
        inner = inner.replace(f"\\begin{{{kind}*}}", f"\\begin{{{kind}}}")
        inner = inner.replace(f"\\end{{{kind}*}}", f"\\end{{{kind}}}")
        if span:
            return "\n\nSPANBEGIN\n\n" + inner + "\n\nSPANEND\n\n"
        return inner
    src = re.sub(r"\\begin{(figure|table)(\*?)}\[[^]]*\].*?\\end{\1\*?}", float_env, src, flags=re.S)

    # equations
    eq = 0
    def equation(m):
        nonlocal eq
        env, inner = m.group(1), m.group(2)
        if env == "equation":
            eq += 1
            lab = re.search(r"\\label{([^}]*)}", inner)
            if lab:
                labels[lab.group(1)] = f"({eq})"
            inner = re.sub(r"\\label{[^}]*}", "", inner)
            return f"\\begin{{equation}}{inner}\\end{{equation}}\n\nEQNUM ({eq})\n\n"
        rows = _split_rows(inner)
        first = None
        for row in rows:
            if not row.strip():
                continue
            if r"\nonumber" in row:
                lab = re.search(r"\\label{([^}]*)}", row)
                if lab:
                    labels[lab.group(1)] = f"({eq + 1})"
                continue
            eq += 1
            first = first or eq
            lab = re.search(r"\\label{([^}]*)}", row)
            if lab:
                labels[lab.group(1)] = f"({eq})"
        inner = re.sub(r"\\label{[^}]*}", "", inner).replace(r"\nonumber", "")
        num = f"({first})" if first == eq else f"({first})\u2013({eq})"
        return f"\\[\\begin{{aligned}}{inner}\\end{{aligned}}\\]\n\nEQNUM {num}\n\n"
    src = re.sub(r"\\begin{(equation|align)}(.*?)\\end{\1}", equation, src, flags=re.S)

    def ref(m):
        key = m.group(2)
        if key not in labels:
            raise KeyError(f"unresolved label {key}")
        val = labels[key]
        if m.group(1) == "eqref":
            return val
        return val
    src = re.sub(r"\\(eqref|ref){([^}]*)}", ref, src)
    src = src.replace("~", " ")

    # squared residuals as sized delimiters so the exponent binds to the group
    src = re.sub(r"(?<![\\\w])\(([^()]*\\hat\\theta[^()]*)\)\^2", r"\\left(\1\\right)^2", src)
    # bare absolute-value bars and half-open intervals come out as unknown
    # glyphs in some Word viewers, so they are written as sized delimiters
    src = re.sub(r"(?<![\\|])\|((?:\\mathcal ?\{?[AW]\}?_?t?|\\hat\\mu_0-\\hat\\mu_1))\|", r"\\left|\1\\right|", src)
    src = src.replace("[kH,(k+1)H)", r"\left[kH,(k+1)H\right)")
    src = re.sub(
        r"\\input{(tables/[^}]*)}",
        lambda m: (PAPER / (m.group(1) + ".tex")).read_text(),
        src,
    )
    src = src.replace("$<$", r"\textless{}").replace(r"$\le$", "\u2264")
    # pandoc cannot read adjustbox or IEEE-only spacing commands
    src = re.sub(r"\\begin{adjustbox}{[^}]*}", "", src)
    src = src.replace(r"\end{adjustbox}", "")
    src = re.sub(r"\\includegraphics\[[^]]*\]{", r"\\includegraphics{", src)

    shim = (PAPER / "docx_shim.tex").read_text()
    macros = (PAPER / "tables" / "macros.tex").read_text()
    latex = (
        shim + macros
        + "\n\nABSTRACTIJIES\n\n" + ABSTRACT_IJIES.strip()
        + "\n\nABSTRACTFUTECH\n\n" + ABSTRACT_FUTECH.strip()
        + "\n\nBODYBEGIN\n\n" + src
    )
    return Prepared(latex=latex, keywords=keywords)


def run_pandoc(latex: str, out: Path) -> None:
    tex = PAPER / ".body_templates.tex"
    tex.write_text(latex)
    cmd = [
        "pandoc", str(tex), "--from", "latex", "--to", "docx",
        f"--resource-path={PAPER}:{PAPER / 'figures'}:{PAPER / 'tables'}",
        "--citeproc", "--bibliography", str(PAPER / "refs.bib"), "--csl", str(PAPER / "ieee.csl"),
        "-o", str(out),
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, cwd=PAPER)
    if res.returncode != 0:
        sys.exit(res.stderr)
    if res.stderr.strip():
        print(res.stderr.strip())
    tex.unlink()


