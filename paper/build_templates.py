#!/usr/bin/env python3
"""Render the shared manuscript body into journal Word templates.

Usage (from anywhere, pandoc >= 3 on PATH, python-docx installed):

    python paper/build_templates.py            # both templates
    python paper/build_templates.py ijies      # one of: ijies, futech

Inputs are body.tex, tables/*.tex (generated by scripts/build_paper_tables.py),
figures/*.png, refs.bib and the two publisher templates in templates/.
Outputs are DES_UCB_IJIES.docx and DES_UCB_Futech.docx next to this file.

Pipeline. body.tex is rewritten so that every \\ref, \\eqref and equation
number is resolved to literal text (Word has no LaTeX counters), the
IEEE-only front matter is removed and template-specific abstracts are added.
pandoc turns that LaTeX into an intermediate .docx (OMML equations, tables,
IEEE-numbered references). The intermediate paragraphs are then re-set into
the publisher template with that template's fonts, sizes, caption forms and
two-column section layout, so headers, footers, margins and styles of the
template are kept untouched.
"""
