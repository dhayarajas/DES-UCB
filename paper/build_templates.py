def _el(tag: str, **attrs) -> OxmlElement:
    e = OxmlElement(tag)
    for k, v in attrs.items():
        e.set(qn(k), str(v))
    return e


def _rpr(font: str, pt: float, bold=None, italic=None, sup=False) -> OxmlElement:
    rpr = OxmlElement("w:rPr")
    fonts = _el("w:rFonts", **{"w:ascii": font, "w:hAnsi": font, "w:cs": font})
    rpr.append(fonts)
    if bold:
        rpr.append(OxmlElement("w:b"))
    if italic:
        rpr.append(OxmlElement("w:i"))
    hp = str(int(round(pt * 2)))
    rpr.append(_el("w:sz", **{"w:val": hp}))
    rpr.append(_el("w:szCs", **{"w:val": hp}))
    if sup:
        rpr.append(_el("w:vertAlign", **{"w:val": "superscript"}))
    return rpr


def _run(text: str, font: str, pt: float, bold=None, italic=None, sup=False) -> OxmlElement:
    r = OxmlElement("w:r")
    r.append(_rpr(font, pt, bold, italic, sup))
    if text == "\t":
        r.append(OxmlElement("w:tab"))
    else:
        t = _el("w:t", **{"xml:space": "preserve"})
        t.text = text
        r.append(t)
    return r


def _ppr(align=None, before=0, after=0, first_line=None, left=None, hanging=None,
         keep_next=False, tabs=None, line=240) -> OxmlElement:
    ppr = OxmlElement("w:pPr")
    if keep_next:
        ppr.append(OxmlElement("w:keepNext"))
    if tabs:
        t = OxmlElement("w:tabs")
        for val, pos in tabs:
            t.append(_el("w:tab", **{"w:val": val, "w:pos": pos}))
        ppr.append(t)
    ppr.append(_el("w:spacing", **{"w:before": before, "w:after": after,
                                   "w:line": line, "w:lineRule": "auto"}))
    ind = {}
    if first_line is not None:
        ind["w:firstLine"] = first_line
    if left is not None:
        ind["w:left"] = left
    if hanging is not None:
        ind["w:hanging"] = hanging
    if ind:
        ppr.append(_el("w:ind", **ind))
    if align:
        ppr.append(_el("w:jc", **{"w:val": align}))
    return ppr


def _para(ppr: OxmlElement, runs: list[OxmlElement]) -> OxmlElement:
    p = OxmlElement("w:p")
    p.append(ppr)
    for r in runs:
        p.append(r)
    return p


def normalise_runs(container, font: str, pt: float, keep_style_size=False) -> None:
    """Re-set every run under ``container`` in the template font and size.

    Bold, italic and super/subscript from pandoc are kept. Verbatim runs get
    Courier New. Math runs keep their Cambria Math font and get the size only.
    """
    hp = str(int(round(pt * 2)))
    for r in container.iter(qn("w:r")):
        in_math = any(a.tag.startswith("{%s}" % M_NS) for a in r.iterancestors())
        rpr = r.find(qn("w:rPr"))
        if rpr is None:
            rpr = OxmlElement("w:rPr")
            r.insert(0, rpr)
        style = rpr.find(qn("w:rStyle"))
        code = style is not None and "Verbatim" in (style.get(qn("w:val")) or "")
        keep = {}
        for tag in ("w:b", "w:i", "w:vertAlign", "w:u", "w:strike"):
            e = rpr.find(qn(tag))
            if e is not None:
                keep[tag] = e
        for child in list(rpr):
            rpr.remove(child)
        if not in_math:
            f = "Courier New" if code else font
            rpr.append(_el("w:rFonts", **{"w:ascii": f, "w:hAnsi": f, "w:cs": f}))
        for tag in ("w:b", "w:i", "w:u", "w:strike", "w:vertAlign"):
            if tag in keep:
                rpr.append(keep[tag])
        rpr.append(_el("w:sz", **{"w:val": hp}))
        rpr.append(_el("w:szCs", **{"w:val": hp}))


def unwrap_hyperlinks(el) -> None:
    for h in list(el.iter(qn("w:hyperlink"))):
        parent = h.getparent()
        idx = parent.index(h)
        for child in list(h):
            parent.insert(idx, child)
            idx += 1
        parent.remove(h)


def para_text(p) -> str:
    return "".join(t.text or "" for t in p.iter(qn("w:t")))


def content_children(p) -> list:
    """Run-level children of a paragraph (everything except pPr)."""
    return [c for c in p if c.tag != qn("w:pPr")]


# --------------------------------------------------------------------------
# 4. Writer
# --------------------------------------------------------------------------
class Writer:
    def __init__(self, spec: Spec, src_docx: Path, keywords: str):
        self.spec = spec
        self.doc = docx.Document(str(spec.template))
        self.src = docx.Document(str(src_docx))
        self.src_zip = zipfile.ZipFile(src_docx)
        self.keywords = keywords
        self.body = self.doc.element.body
        self.fig = 0
        self.tab = 0
        self.h1 = 0
        self.h2 = 0
        self.image_cache: dict[str, str] = {}
        self.ref_pars: list = []
        # relationship id -> media path in the pandoc package
        rels = self.src.part.rels
        self.src_media = {rid: rel.target_part for rid, rel in rels.items()
                          if rel.reltype.endswith("/image")}

    # -- section geometry -------------------------------------------------
    def _two_col_sectpr(self):
        for sp in self.body.iter(qn("w:sectPr")):
            cols = sp.find(qn("w:cols"))
            if cols is not None and cols.get(qn("w:num")) == "2":
                return sp
        raise RuntimeError("template has no two-column section")

    def geometry(self):
        sp = self._two_col_sectpr()
        pg = sp.find(qn("w:pgSz")); mar = sp.find(qn("w:pgMar")); cols = sp.find(qn("w:cols"))
        text_w = int(pg.get(qn("w:w"))) - int(mar.get(qn("w:left"))) - int(mar.get(qn("w:right")))
        gap = int(cols.get(qn("w:space")))
        col_w = (text_w - gap) // 2
        return text_w, col_w  # twips

    def _sect_break(self, num_cols: int):
        """Paragraph carrying a continuous section break for the section that ends here."""
        sp = copy.deepcopy(self._two_col_sectpr())
        for tag in ("w:headerReference", "w:footerReference"):
            for e in sp.findall(qn(tag)):
                sp.remove(e)
        cols = sp.find(qn("w:cols"))
        if num_cols == 1:
            if cols.get(qn("w:num")) is not None:
                del cols.attrib[qn("w:num")]
        else:
            cols.set(qn("w:num"), "2")
        t = sp.find(qn("w:type"))
        if t is None:
            t = OxmlElement("w:type"); sp.insert(0, t)
        t.set(qn("w:val"), "continuous")
        ppr = _ppr(after=0)
        ppr.append(sp)
        p = OxmlElement("w:p"); p.append(ppr)
        return p

    # -- element emission --------------------------------------------------
    def emit(self, el) -> None:
        self.body.insert(len(self.body) - 1, el)  # before the body sectPr

    def emit_par(self, ppr, runs, pt=None):
        p = _para(ppr, runs)
        self.emit(p)
        return p

    def text_par(self, text, pt=None, bold=False, italic=False, align="both",
                 before=0, after=0, first_line=None, keep_next=False):
        pt = pt or self.spec.body_pt
        return self.emit_par(_ppr(align=align, before=before, after=after,
                                  first_line=first_line, keep_next=keep_next),
                             [_run(text, self.spec.font, pt, bold, italic)])

    # -- images -------------------------------------------------------------
    def relink_images(self, el, max_width_twips: int) -> None:
        for blip in el.iter("{%s}blip" % A_NS):
            rid = blip.get("{%s}embed" % R_NS)
            if rid not in self.image_cache:
                part = self.src_media[rid]
                new_rid, _ = self.doc.part.get_or_add_image(io.BytesIO(part.blob))
                self.image_cache[rid] = new_rid
            blip.set("{%s}embed" % R_NS, self.image_cache[rid])
        max_emu = max_width_twips * 635
        for ext in el.iter("{%s}extent" % WP_NS):
            cx, cy = int(ext.get("cx")), int(ext.get("cy"))
            if cx > max_emu:
                scale = max_emu / cx
                cx, cy = int(cx * scale), int(cy * scale)
            ext.set("cx", str(cx)); ext.set("cy", str(cy))
            drawing = next(a for a in ext.iterancestors() if a.tag == qn("w:drawing"))
            for aext in drawing.iter("{%s}ext" % A_NS):
                aext.set("cx", str(cx)); aext.set("cy", str(cy))

    # -- front matter --------------------------------------------------------
    def clear_par(self, p, keep_ppr=True):
        for c in list(p):
            if c.tag == qn("w:pPr") and keep_ppr:
                # drop paragraph-mark colour/superscript so nothing red survives
                rpr = c.find(qn("w:rPr"))
                if rpr is not None:
                    for tag in ("w:color", "w:vertAlign"):
                        e = rpr.find(qn(tag))
                        if e is not None:
                            rpr.remove(e)
                continue
            p.remove(c)

    def fill_par(self, p, pieces, font, pt):
        """pieces: list of (text, bold, italic, superscript) or lxml run-level elements."""
        self.clear_par(p)
        for piece in pieces:
            if isinstance(piece, tuple):
                text, b, i, s = piece
                p.append(_run(text, font, pt, b, i, s))
            else:
                p.append(piece)

    # -- body conversion -----------------------------------------------------
    def convert_body(self, elements: list) -> None:
        text_w, col_w = self.geometry()
        span = False
        pending_caption = None  # for tables: caption comes before the table
        i = 0
        while i < len(elements):
            el = elements[i]
            i += 1
            if el.tag == qn("w:tbl"):
                self.tab += 1
                if pending_caption is not None:
                    self.emit(pending_caption)
                    pending_caption = None
                self.emit_table(el, text_w if span else col_w)
                continue
            if el.tag != qn("w:p"):
                continue
            style = self._style(el).lower()
            text = para_text(el).strip()
            if text == "SPANBEGIN":
                self.emit(self._sect_break(2)); span = True; continue
            if text == "SPANEND":
                self.emit(self._sect_break(1)); span = False; continue
            if text.startswith("EQNUM"):
                self.attach_eq_number(text.split(None, 1)[1]); continue
            if style.startswith("heading"):
                if style == "heading 1" and text.lower() in ("references", "bibliography"):
                    continue
                self.emit_heading(style, el); continue
            if style in ("image caption", "caption"):
                self.emit_caption(el, "fig", col_w if not span else text_w); continue
            if style == "table caption":
                pending_caption = self.make_caption(el, "tab", text_w if span else col_w); continue
            if style == "bibliography":
                self.emit_reference(el); continue
            has_img = el.find(".//" + qn("w:drawing")) is not None
            if has_img:
                self.emit_image_par(el, text_w if span else col_w); continue
            has_display_math = el.find(qn("m:oMathPara")) is not None or el.find(".//" + qn("m:oMathPara")) is not None
            if has_display_math:
                self.emit_display_math(el, text_w if span else col_w); continue
            self.emit_body_par(el, style)

    def _style(self, p) -> str:
        ps = p.find(qn("w:pPr"))
        if ps is None:
            return "Normal"
        s = ps.find(qn("w:pStyle"))
        if s is None:
            return "Normal"
        sid = s.get(qn("w:val"))
        try:
            return self.src.styles.element.get_by_id(sid).name_val or sid
        except AttributeError:
            return sid

    def _runs_of(self, p, pt):
        p = copy.deepcopy(p)
        unwrap_hyperlinks(p)
        normalise_runs(p, self.spec.font, pt)
        return content_children(p)

    def emit_body_par(self, p, style):
        runs = self._runs_of(p, self.spec.body_pt)
        if not runs:
            return
        self.emit_par(_ppr(align="both", first_line=self.spec.first_line_indent, after=0), runs)

    def emit_heading(self, style, p):
        spec = self.spec
        text = para_text(p).strip()
        if style == "heading 1":
            self.h1 += 1; self.h2 = 0
            label = f"{self.h1}. {text}"
            self.emit_par(_ppr(align="left", before=240, after=120, keep_next=True),
                          [_run(label, spec.font, spec.h1_pt, bold=True)])
        elif style == "heading 2":
            self.h2 += 1
            label = f"{self.h1}.{self.h2}. {text}"
            self.emit_par(_ppr(align="left", before=180, after=100, keep_next=True),
                          [_run(label, spec.font, spec.h2_pt, bold=True)])
        else:
            self.emit_par(_ppr(align="left", before=120, after=60, keep_next=True),
                          [_run(text, spec.font, spec.body_pt, bold=True, italic=True)])

    def make_caption(self, p, kind, width):
        spec = self.spec
        runs = self._runs_of(p, spec.caption_pt)
        # drop a pandoc-generated "Figure 1: " or "Table 1: " prefix if present
        first_t = next((t for t in _para(_ppr(), runs).iter(qn("w:t"))), None)
        if first_t is not None and first_t.text:
            first_t.text = re.sub(r"^(Figure|Table)\s*\d+[:.]?\s*", "", first_t.text)
        if kind == "fig":
            self.fig += 1
            prefix = spec.fig_prefix.format(n=self.fig)
        else:
            prefix = spec.tab_prefix.format(n=self.tab + 1)
        ppr = _ppr(align="center", before=60, after=120 if kind == "fig" else 60,
                   keep_next=(kind == "tab"))
        return _para(ppr, [_run(prefix, spec.font, spec.caption_pt, bold=True)] + runs)

    def emit_caption(self, p, kind, width):
        self.emit(self.make_caption(p, kind, width))

    def emit_image_par(self, p, width):
        p = copy.deepcopy(p)
        self.relink_images(p, width)
        for c in list(p):
            if c.tag == qn("w:pPr"):
                p.remove(c)
        p.insert(0, _ppr(align="center", before=120, after=60, keep_next=True))
        # strip caption runs pandoc may leave inline, keep drawings only
        for r in list(p.iter(qn("w:r"))):
            if r.find(".//" + qn("w:drawing")) is None:
                r.getparent().remove(r)
        self.emit(p)

    def emit_display_math(self, p, width):
        spec = self.spec
        p = copy.deepcopy(p)
        normalise_runs(p, spec.font, spec.body_pt)
        # alignment marks inside equation arrays render as stray symbols in
        # some viewers, so each row is simply centred
        for t in list(p.iter(qn("m:t"))):
            if t.text and "&" in t.text:
                t.text = t.text.replace("&", "")
            if not t.text:
                r = t.getparent()
                r.getparent().remove(r)
        maths = list(p.iter(qn("m:oMathPara")))
        for mp in maths:
            parent = mp.getparent()
            idx = parent.index(mp)
            for om in list(mp.findall(qn("m:oMath"))):
                parent.insert(idx, om); idx += 1
            parent.remove(mp)
        for c in list(p):
            if c.tag == qn("w:pPr"):
                p.remove(c)
        right = width
        p.insert(0, _ppr(align="left", before=60, after=60,
                         tabs=[("center", str(right // 2)), ("right", str(right))]))
        p.insert(1, _run("\t", spec.font, spec.body_pt))
        self._last_math = p
        self.emit(p)

    def attach_eq_number(self, num):
        p = self._last_math
        p.append(_run("\t", self.spec.font, self.spec.body_pt))
        p.append(_run(num, self.spec.font, self.spec.body_pt))

    def emit_reference(self, p):
        spec = self.spec
        runs = self._runs_of(p, spec.ref_pt)
        # pandoc bibliography entries carry the "[n]" label then a tab
        p = self.emit_par(_ppr(align="both", left=440, hanging=440, after=40,
                               tabs=[("left", "440")]), runs)
        self.ref_pars.append(p)

    def emit_table(self, tbl, width):
        spec = self.spec
        tbl = copy.deepcopy(tbl)
        unwrap_hyperlinks(tbl)
        normalise_runs(tbl, spec.font, spec.table_pt)
        tblpr = tbl.find(qn("w:tblPr"))
        if tblpr is None:
            tblpr = OxmlElement("w:tblPr"); tbl.insert(0, tblpr)
        for tag in ("w:tblStyle", "w:tblW", "w:jc", "w:tblBorders", "w:tblLook", "w:tblInd"):
            for e in tblpr.findall(qn(tag)):
                tblpr.remove(e)
        tblpr.insert(0, _el("w:tblStyle", **{"w:val": self._table_style_id()}))
        tblpr.append(_el("w:tblW", **{"w:w": str(width), "w:type": "dxa"}))
        tblpr.append(_el("w:jc", **{"w:val": "center"}))
        tblpr.append(_el("w:tblLayout", **{"w:type": "autofit"}))
        # grid widths proportional to the longest entry of each column, so
        # numeric columns stay narrow and text columns get the room
        rows = tbl.findall(qn("w:tr"))
        ncol = max(len(r.findall(qn("w:tc"))) for r in rows)
        longest = [1] * ncol
        for r in rows:
            for j, tc in enumerate(r.findall(qn("w:tc"))):
                words = para_text(tc).split()
                est = min(max([len(x) for x in words] + [0]) + 2 + len(para_text(tc)) // 4, 40)
                longest[j] = max(longest[j], est)
        total = sum(longest)
        widths = [max(500, width * l // total) for l in longest]
        scale = width / sum(widths)
        widths = [int(x * scale) for x in widths]
        grid = tbl.find(qn("w:tblGrid"))
        if grid is None:
            grid = OxmlElement("w:tblGrid"); tblpr.addnext(grid)
        for gc in list(grid):
            grid.remove(gc)
        for wdt in widths:
            grid.append(_el("w:gridCol", **{"w:w": str(wdt)}))
        for r in rows:
            for j, tc in enumerate(r.findall(qn("w:tc"))):
                tcpr = tc.find(qn("w:tcPr"))
                if tcpr is None:
                    tcpr = OxmlElement("w:tcPr"); tc.insert(0, tcpr)
                for e in tcpr.findall(qn("w:tcW")):
                    tcpr.remove(e)
                tcpr.insert(0, _el("w:tcW", **{"w:w": str(widths[j]), "w:type": "dxa"}))
        for tc in tbl.iter(qn("w:tc")):
            for p in tc.findall(qn("w:p")):
                ppr = p.find(qn("w:pPr"))
                if ppr is not None:
                    p.remove(ppr)
                p.insert(0, _ppr(after=0, line=240))
        self.emit(tbl)
        self.emit_par(_ppr(after=120), [])

    def _table_style_id(self) -> str:
        for s in self.doc.styles:
            if s.name == "Table Grid":
                return s.style_id
        # create a minimal grid style if the template lacks one
        st = self.doc.styles.add_style("Table Grid", docx.enum.style.WD_STYLE_TYPE.TABLE)
        borders = parse_xml(
            '<w:tblBorders %s>' % nsdecls("w")
            + "".join(f'<w:{b} w:val="single" w:sz="4" w:space="0" w:color="auto"/>'
                      for b in ("top", "left", "bottom", "right", "insideH", "insideV"))
            + "</w:tblBorders>")
        tblpr = st.element.get_or_add_tblPr()
        tblpr.append(borders)
        return st.style_id

    # -- back matter ---------------------------------------------------------
    def emit_back_matter(self):
        spec = self.spec
        for head, text in spec.back_matter:
            self.emit_par(_ppr(align="left", before=240, after=120, keep_next=True),
                          [_run(head, spec.font, spec.h1_pt, bold=True)])
            self.text_par(text, first_line=spec.first_line_indent)

    def save(self):
        self.doc.save(str(self.spec.output))
        print("wrote", self.spec.output.relative_to(PAPER.parent))


